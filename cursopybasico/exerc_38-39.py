pv = input("Digite o primeiro valor: ")
sv = input("Digite o segundo valor: ")

if pv > sv:
    print(f"{pv} é maior que {sv}")
elif pv == sv:
    print(f"{pv} é igual a {sv}")
else:
    print(f"{pv} é menor que {sv}")



